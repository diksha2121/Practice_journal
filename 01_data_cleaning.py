import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("/content/messy_retail_orders.csv")

df.head()

df.shape

df.info()

"""handle incorrect data types, missing values, duplicates"""

df.duplicated().sum()

df.isnull().sum()

df.dtypes

df.head(1)

"""1. Handling Incorrect Datatypes"""

#Converting order_date to datetime datatype
df['order_date'] = pd.to_datetime(df['order_date'], errors = 'coerce')

#Converting 'quantity' to int datatype
df['quantity'] = df['quantity'].astype(str).str.replace('units', '', regex=False).str.strip().astype(int)
df['quantity'].dtype

#Converting 'unit_price' to float datatype
df['unit_price'] = df['unit_price'].astype(str).str.replace('$', '', regex=False).str.replace('USD', '', regex=False).str.strip().astype(float)
df['unit_price'].dtype

#Converting 'discount_pct' tp float datatype
df['discount_pct'] = df['discount_pct'].astype(str).str.replace('%', '', regex=False).str.strip().astype(float)
df['discount_pct'].dtype

#Converting 'order_total' to float datatype
df['order_total'] = df['order_total'].astype(str).str.replace('USD', '', regex=False).str.replace('$', '', regex=False).str.strip().astype(float)
df['order_total'].dtype

#Converting delivery_date to datetime datatype
df['delivery_date'] = pd.to_datetime(df['delivery_date'], errors='coerce')
df['delivery_date'].dtype

"""2. Handling Duplicates"""

df.duplicated().sum()

df.drop_duplicates().shape

df.drop_duplicates(inplace=True)

df.shape

"""3. Handling Missing Values"""

df.isnull().sum()

#Filling missing 'order_date' values
avg_delivery_days = (df['delivery_date'] - df['order_date']).dt.days.mean()
ship_time = pd.Timedelta(days=round(avg_delivery_days))
df['order_date'] = df['order_date'].fillna(df['delivery_date'] - ship_time)
#Filling missing 'delivery_date' values
df['delivery_date'] = df['delivery_date'].fillna(df['order_date'] + ship_time)
#Drop rows where both 'order_date' and 'delivery_date' values are missing
df = df.dropna(subset=['order_date', 'delivery_date'], how='all')

#Filling 'customer_segment' with 'Unknown'
df.loc[:, 'customer_segment'] = df['customer_segment'].fillna('Unknown')

#Filling 'product_name' with 'Unknown'
df.loc[:, 'product_name'] = df['product_name'].fillna('Unknown')

#Filling 'category' with mode imputation
df.loc[:, 'category'] = df['category'].fillna(df['category'].mode()[0])

df[['quantity', 'unit_price', 'discount_pct', 'order_total']]

# Fill missing unit_price when discount_pct is available
mask = df["unit_price"].isna() & df["discount_pct"].notna()

df.loc[mask, "unit_price"] = (df.loc[mask, "order_total"]/ (df.loc[mask, "quantity"]* (1 - df.loc[mask, "discount_pct"] / 100))).round(2)

# Fill missing discount_pct when unit_price is available
mask = df["discount_pct"].isna() & df["unit_price"].notna()

df.loc[mask, "discount_pct"] = ((1 - df.loc[mask, "order_total"]/ (df.loc[mask, "quantity"] * df.loc[mask, "unit_price"])) * 100).round(2)

#Fill missing 'payment_method' values
df.loc[:, 'payment_method'] = df['payment_method'].fillna('Other')

#Fill missing 'city' values
df.loc[:, 'city'] = df['city'].fillna('Unknown')

sns.histplot(data=df, x='shipping_days', kde=True)
plt.show()

df.loc[:, 'shipping_days'] = df['shipping_days'].fillna(df['shipping_days'].median())

df['shipping_days'].median()

df['customer_rating'].value_counts(dropna=False)

df['customer_rating'].median()

sns.histplot(data=df, x='customer_rating', kde=True)
plt.show()

#Fill missing customer_rating using median
df.loc[:, 'customer_rating'] = df['customer_rating'].fillna(df['customer_rating'].median())

df['sales_rep'].value_counts(dropna=False)

#Fill missing 'sales_rep' values
df.loc[:, 'sales_rep'] = df['sales_rep'].fillna('Unassigned')

